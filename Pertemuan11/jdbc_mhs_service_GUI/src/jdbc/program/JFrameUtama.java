    private void getAllActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_getAllActionPerformed
        // TODO add your handling code here:
        String nama = txtAddNama.getText().trim();
        
        if (!nama.isEmpty()) {
            Mahasiswa mhs = service.makeMhsObject();
            mhs.setNama(nama);
            service.add(mhs);

            txtAddNama.setText("");
            refreshData();
            lblStatus.setText("Data " + nama + " berhasil ditambahkan.");
        }
        else {
            lblStatus.setText("Nama tidak boleh kosong");
        }
    }//GEN-LAST:event_getAllActionPerformed

    private void DeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteActionPerformed
        // TODO add your handling code here:
        try {
            String idText = txtIDDelete.getText().trim();
            
            if (!idText.isEmpty()) {
                int id = Integer.parseInt(idText);
                service.delete(id);
                txtIDDelete.setText("");
                refreshData();
                lblStatus.setText("Data ID " + id + " berhasil dihapus.");
            }
            else {
                lblStatus.setText("ID Hapus tidak boleh kosong!");
            }
        } catch (NumberFormatException e) {
            lblStatus.setText("ID harus berupa angka!");
        }
    }//GEN-LAST:event_DeleteActionPerformed

