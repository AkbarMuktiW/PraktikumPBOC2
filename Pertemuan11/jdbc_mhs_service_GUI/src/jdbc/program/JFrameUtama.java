    private void UpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateActionPerformed
        // TODO add your handling code here:
        try {
            String idText = txtIDEdit.getText().trim();
            String nama = txtNamaEdit.getText().trim();
            
            if (!idText.isEmpty() && !nama.isEmpty()) {
                int id = Integer.parseInt(idText);
                Mahasiswa mhs = service.makeMhsObject();
                mhs.setId(id);
                mhs.setNama(nama);

                service.update(mhs);
                txtIDEdit.setText("");
                txtNamaEdit.setText("");
                refreshData();
                lblStatus.setText("Data ID " + id + " berhasil diubah.");
            }
            else {
                lblStatus.setText("ID dan Nama Edit tidak boleh kosong!");
            }
        } catch (NumberFormatException e) {
            lblStatus.setText("ID harus berupa angka");
        }
    }//GEN-LAST:event_UpdateActionPerformed

